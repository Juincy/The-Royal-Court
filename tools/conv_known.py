import re,sys
src=open('/home/claude/rc2/src/core.hpp',encoding='utf-8').read().split('\n')
body='\n'.join(src[1718:1936])   # lines 1719..1936 (inside builtinKnownMods)
# tokenise
tok=re.compile(r'(?P<str>"(?:[^"\\]|\\.)*"(?:\s*"(?:[^"\\]|\\.)*")*)|(?P<cmt>//[^\n]*)|(?P<o>.)',re.S)
def dec(run):
    parts=re.findall(r'"((?:[^"\\]|\\.)*)"',run,re.S)
    bs=bytearray()
    for p in parts:
        i=0
        while i<len(p):
            c=p[i]
            if c=='\\':
                n=p[i+1]
                if n=='x':
                    bs.append(int(p[i+2:i+4],16)); i+=4
                elif n=='n': bs+=b'\n'; i+=2
                elif n=='t': bs+=b'\t'; i+=2
                elif n in '"\\\'': bs+=n.encode(); i+=2
                else: raise Exception('esc '+p)
            else:
                bs+=c.encode('utf-8'); i+=1
    s=bs.decode('utf-8')
    o=[]
    for ch in s:
        if ch=='"': o.append('\\"')
        elif ch=='\\': o.append('\\\\')
        elif ch=='\n': o.append('\\n')
        elif ord(ch)>126: o.append('\\u%04x'%ord(ch))
        else: o.append(ch)
    return '"'+''.join(o)+'"'
out=[]
for m in tok.finditer(body):
    if m.group('str'): out.append(dec(m.group('str')))
    else: out.append(m.group(0))
t=''.join(out)
t=t.replace('{ KnownMod k;','{ var k = new KnownMod();').replace('KnownMod k; k.names','var k = new KnownMod(); k.names')
for a,b in [('names','Names'),('ids','Ids'),('after','After'),('before','Before')]:
    t=re.sub(r'k\.%s = \{'%a,'k.%s = new() {'%b,t)
t=re.sub(r'k\.cat = CAT_(\w+)',lambda m:'k.Cat = Cat.'+m.group(1).capitalize(),t)
t=t.replace('k.pos =','k.Pos =').replace('k.rank =','k.Rank =').replace('k.note =','k.Note =')
t=t.replace('v.push_back(k)','v.Add(k)')
t=re.sub(r'for \(const char\* (\w+) : \{([^}]*)\}\)',r'foreach (var \1 in new[] {\2})',t)
t=re.sub(r'for \(auto id_name : std::vector<std::pair<const char\*, const char\*>>\{(.*?)\}\) \{',lambda m:'foreach (var id_name in new (string, string)[] {'+re.sub(r'\{("[^"]*"), ("[^"]*")\}',r'(\1, \2)',m.group(1))+'}) {',t)
t=t.replace('id_name.second','id_name.Item2').replace('if (id_name.first[0]) k.Ids = new() {id_name.first};','if (id_name.Item1.Length > 0) k.Ids = new() {id_name.Item1};')
# drop the final normalisation loop and return
t=re.sub(r'    for \(auto& k : v\) \{ for.*?\n    return v;\n?','',t,flags=re.S)
open('/tmp/known_body.cs','w').write(t)
print(t.count('var k = new KnownMod'), 'entries (incl loops)')

# ---- assemble KnownData.cs ----
lines=t.split('\n')
lines=lines[1:]   # drop std::vector<KnownMod> v;
cut=[i for i,l in enumerate(lines) if 'names are compared in their normalised form' in l][0]
body='\n'.join(lines[:cut])
# compat patches
cp=src[2011:2040]   # lines 2012..2040
cps=[]
for l in cp:
    l=l.strip()
    if not l.startswith('{"'): continue
    l=re.sub(r'"(?:[^"\\]|\\.)*"',lambda m:dec(m.group(0)),l)
    m=re.match(r'\{("[^"]*"), ("[^"]*"), (\{.*\})\},$',l)
    par=m.group(3).replace('{','new[] {')
    cps.append('        new(%s, %s, %s),'%(m.group(1),m.group(2),par))
cs='''// GENERATED by tools/conv_known.py from core.hpp (builtinKnownMods and compatPatches). Do not edit by hand.
namespace RoyalCourt.Core;

public static partial class KnownData
{
    public static List<KnownMod> Builtin()
    {
        var v = new List<KnownMod>();
%s
        foreach (var k in v) { k.Names = k.Names.Select(Names.Norm).ToList(); k.After = k.After.Select(Names.Norm).ToList(); k.Before = k.Before.Select(Names.Norm).ToList(); }
        return v;
    }

    public static readonly CompatPatch[] Patches =
    {
%s
    };
}
'''%(body,'\n'.join(cps))
open('/home/claude/rc-cs/src/RoyalCourt.Core/KnownData.cs','w',encoding='utf-8').write(cs)
print(len(cps),'patches')
