#!/usr/bin/env python3
"""Writes src/RoyalCourt.Core/KnownChecked.cs from tools/workshop_ledger.json: the Workshop ids whose page we READ and that state no load order we use
(so the program can say "checked: no order needed" instead of "unknown"). Run after every Workshop batch:  python3 tools/gen_checked.py"""
import json,os
here=os.path.dirname(os.path.abspath(__file__))
L=json.load(open(os.path.join(here,"workshop_ledger.json"),encoding="utf-8"))["items"]
ids=sorted({e["id"] for e in L if e.get("status")=="read" and e["id"].isdigit()})
lines=[]; row=[]
for i in ids:
    row.append('"%s"'%i)
    if len(row)==8: lines.append("        "+", ".join(row)+","); row=[]
if row: lines.append("        "+", ".join(row)+",")
out="""// Generated by tools/gen_checked.py from the Workshop ledger. Do not edit by hand.
namespace RoyalCourt.Core;

/// <summary>Workshop pages that were read for load-order statements ({0} pages). A mod on this list with no rule of its own is "checked": its page says nothing about order.</summary>
public static class KnownChecked
{{
    public static readonly HashSet<string> Ids = new(StringComparer.Ordinal)
    {{
{1}
    }};
}}
""".format(len(ids),"\n".join(lines))
open(os.path.join(here,"..","src","RoyalCourt.Core","KnownChecked.cs"),"w",encoding="utf-8").write(out)
print(len(ids),"ids")
